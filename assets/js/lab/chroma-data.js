// Хроматографія: види, приклади сумішей та параметри утримування для моделі колонки.
// k — коефіцієнт ємності (k' = (tR − t0)/t0) як функція умов елюювання v.

const lg = Math.log10;

// Сумарний заряд амінокислоти при заданому pH (α-COOH, α-NH3+, бічна група).
function aaCharge(c, pH) {
  let q = 1 / (1 + 10 ** (pH - c.pk2)) - 1 / (1 + 10 ** (c.pk1 - pH));
  if (c.pkr && c.side === 'a') q -= 1 / (1 + 10 ** (c.pkr - pH));
  if (c.pkr && c.side === 'b') q += 1 / (1 + 10 ** (pH - c.pkr));
  return q;
}

// Стоксів радіус глобулярного білка, нм (емпірично, M у Да).
export const stokes = (M) => 0.0515 * M ** 0.392;
// Коефіцієнт дифузії в розчині, мм²/с (рівняння Стокса–Ейнштейна, вода 20 °C).
export const diffusion = (M) => 2.45e-4 / Math.max(0.2, stokes(M));

