// Ексклюзійна: K_d = (1 − r_s/r_p)² для циліндричних пор; k = K_d·V_p/V₀ (V_p/V₀ ≈ 1,43).
export const SEC_VP_V0 = 1.43;
export function secKd(c, rp) { const r = stokes(c.M); return r >= rp ? 0 : (1 - r / rp) ** 2; }
function secK(c, rp) { return secKd(c, rp) * SEC_VP_V0; }

