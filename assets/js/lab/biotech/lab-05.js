    function calcA(rpm = stateA.rpm, fill = stateA.fill, aux = stateA.aux24D, fri = stateA.friab, sieve = stateA.sieve) {
      // Volumetric mass transfer coefficient kLa (h^-1):
      // Scales ~ (rpm/120)^1.45 * (0.20/fill)^0.75 * 14.5
      const kLa = 14.5 * Math.pow(rpm / 120, 1.45) * Math.pow(0.20 / fill, 0.78);
      // Oxygen demand qO2 * X ~ 28 mg/(L*h) at active suspension density
      const O2star = 8.1; // mg/L at 25°C
      const qO2X = 26.0;
      const cO2 = clamp(O2star - qO2X / Math.max(3.6, kLa), 0.4, O2star);
      const o2Pct = (cO2 / O2star) * 100;

      // Shear stress tau (Pa) and mechanical damage (%):
      const tau = 0.18 * Math.pow(rpm / 100, 1.65) * (1 + 0.25 * (0.25 - fill));
      const shearDmg = clamp(100 / (1 + Math.exp(-(rpm - 172) / 14)), 0.5, 95);

      // Disaggregation index D_idx in [0..1]:
      const rpmEffect = smooth(60, 165, rpm);
      const auxEffect = smooth(0.2, 2.2, aux);
      let dIdx = clamp(0.32 * rpmEffect + 0.36 * auxEffect + 0.32 * fri, 0, 1);
      if (sieve === "250") dIdx = clamp(dIdx + 0.22, 0, 1);
      if (sieve === "100") dIdx = clamp(dIdx + 0.45, 0, 1);

      // Textbook fractions:
      // Coarse (dIdx -> 0): Single = 0%, Small = 40%, Large = 60%
      // Medium (dIdx ~ 0.55): Single = 40%, Small = 40%, Large = 20%
      // Fine (dIdx -> 1.0): Single = 40..45%, Small = 60..55%, Large = 0%
      let fLarge = clamp(60 * Math.pow(1 - dIdx, 1.35), 0, 65);
      if (sieve === "250") fLarge *= 0.25;
      if (sieve === "100") fLarge = 0;
      let fSingle = clamp(42 * smooth(0.08, 0.58, dIdx), 0, 48);
      let fSmall = clamp(100 - fSingle - fLarge, 0, 100);
      // Normalize to 100%:
      const sum = fSingle + fSmall + fLarge || 1;
      fSingle = Math.round((fSingle / sum) * 100);
      fLarge = Math.round((fLarge / sum) * 100);
      fSmall = 100 - fSingle - fLarge;

      let typeLabel = "Середня суспензія";
      let typeCls = "good";
      if (fLarge <= 6) {
        typeLabel = "Дрібна суспензія (40 % один. : 60 % дрібн.)";
        typeCls = "good";
      } else if (fLarge >= 38 || fSingle <= 12) {
        typeLabel = "Крупна суспензія (40 % дрібн. : 60 % крупн.)";
        typeCls = "warn";
      } else {
        typeLabel = "Середня суспензія (40 % : 40 % : 20 %)";
        typeCls = "good";
      }
      if (shearDmg > 25) typeCls = "bad";
      else if (o2Pct < 45) typeCls = "warn";

      return { kLa, cO2, o2Pct, tau, shearDmg, fSingle, fSmall, fLarge, typeLabel, typeCls };
    }

