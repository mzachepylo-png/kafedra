    function simC() {
      const Ks = 2.2;    // г/л сахарози
      const Yxs = 0.48;  // г сухої біомаси / г сахарози
      const kd = 0.03;   // доба⁻¹ (ендогенне дихання та відмирання)
      const dt = 0.1;    // доба
      const tMax = 20;   // діб

      const ptsX = [], ptsS = [], ptsMu = [];
      let X = stateC.X0;
      let S = stateC.S0;
      let xPeak = X;
      const D = stateC.mode === "chemostat" ? stateC.D : 0;
      // Critical inoculum effect (lag phase ~ 1.8 days if X0 is normal, longer if X0 < 0.5)
      const lagTau = stateC.X0 < 0.5 ? 3.5 : 1.4;

      for (let t = 0; t <= tMax + 1e-6; t += dt) {
        const lagFactor = stateC.mode === "batch" ? (1 - Math.exp(-Math.pow(t / lagTau, 2))) : 1;
        const mu = stateC.muMax * (S / (Ks + S)) * lagFactor;
        if (Math.abs(t - Math.round(t * 2) / 2) < 1e-4) {
          ptsX.push([+t.toFixed(1), X]);
          ptsS.push([+t.toFixed(1), S]);
          ptsMu.push([+t.toFixed(1), mu]);
        }
        const dX = (mu - kd - D) * X * dt;
        const dS = (D * (stateC.S0 - S) - (mu / Yxs) * X) * dt;
        X = Math.max(0.02, X + dX);
        S = clamp(S + dS, 0, stateC.S0);
        if (X > xPeak) xPeak = X;
      }

      // Steady-state chemostat equations as function of D:
      const Dcrit = Math.max(0.05, stateC.muMax * (stateC.S0 / (Ks + stateC.S0)) - kd);
      const steady = (dVal) => {
        if (dVal >= Dcrit) return { Xss: 0, Sss: stateC.S0, Pss: 0 };
        const muReq = dVal + kd;
        const Sss = clamp((Ks * muReq) / Math.max(1e-4, stateC.muMax - muReq), 0, stateC.S0);
        const Xss = Math.max(0, Yxs * (stateC.S0 - Sss) * (dVal / Math.max(1e-4, muReq)));
        return { Xss, Sss, Pss: dVal * Xss };
      };
      const curSS = steady(stateC.D);
      const tdMin = Math.LN2 / stateC.muMax;

      return { ptsX, ptsS, ptsMu, xPeak, Sfinal: S, Xfinal: X, Dcrit, curSS, steady, tdMin };
    }

