        x: [0, 20], y: [0, Math.max(35, stateC.S0 + 5)],
        xl: "Час культивування t, діб",
        yl: "Біомаса X (г/л) / Сахароза S (г/л)",
        band: !isChem ? [{ x0: 11, x1: 14, color: rgba(T.good, 0.10) }] : [],
