// Тема 6. Клітинна селекція (ЛР 23, с. 93–96). Математика без DOM.
// Посібник: 1 мл суспензії клітин мезофілу тютюну висівають на МС + ІОК 2 мг/л + БАП 0,5 мг/л + стрептоміцин 0,5 мг/мл,
// pH 5,0–5,5; термостат 25–26 °C, абсолютна темрява (утворення калюсу). Стрептоміцин інгібує позеленіння, але НЕ ріст:
// мутантні ділянки виявляють за зеленим кольором. Перевірка: зелені ділянки розмножують на тому ж середовищі; регенерацію
// проводять без антибіотика, але для запобігання химерам — з антибіотиком; спостереження кожні 7 діб (с. 95–96).
// Стабільність (с. 94): 4–6 субкультивувань на селективному середовищі → 2–3 пасажі без селективного фактора →
// повернення в селективні умови; сублетальна концентрація — та, за якої калюс росте, а частина колоній гине.
// Числових констант (частота мутантів, ефективність висіву, IC50) посібник не наводить — нижче наближення моделі.

export const clamp = (x, a, b) => Math.max(a, Math.min(b, x));
export const hill = (c, k, n) => 1 / (1 + Math.pow(Math.max(0, c) / k, n));

/* ---------- ЛР 23: висів і відбір за кольором ---------- */
export const A = {
  V: 1,             // мл суспензії на чашку (посібник)
  PEmax: 0.06,      // максимальна ефективність висіву (частка клітин, що дають колонію) — припущення
  nc: 1e4,          // густина «кондиціювання», клітин/мл: за меншої густини клітини погано діляться — припущення
  icS: 0.02, hS: 1.5, // хлорофіл чутливих колоній: IC50 0,02 мг/мл — припущення
  icR: 5, hR: 2,      // стійкі (мутація в 16S рРНК / білку S12 пластид) — припущення
  icG: 4, hG: 2,      // ріст: стрептоміцин майже не гальмує (посібник) — IC50 4 мг/мл
  dmax: 3, t50: 24, s: 4.5, // діаметр колонії, мм (логістика від доби висіву)
  dark: 28,         // темрява до 28-ї доби (посібник: калюсоутворення в темряві); далі світло — припущення моделі
  tauL: 5,          // стала позеленіння на світлі, діб
  chim: 0.3,        // частка химерних (секторних) серед стійких — припущення
};
export function plating({ n, f, C, k }) {
  const PE = A.PEmax * n / (n + A.nc);
  const N = n * A.V * PE;                  // колоній на чашку
  const lam = N * f;                       // очікувано стійких колоній на чашку (пуассонівське середнє)
  const P = 1 - Math.exp(-k * lam);        // імовірність хоча б однієї стійкої в серії з k чашок
  const k95 = Math.ceil(Math.log(20) / Math.max(lam, 1e-12)); // чашок для P ≥ 95 %
  return { PE, N, lam, P, k95, Gs: hill(C, A.icS, A.hS), Gr: hill(C, A.icR, A.hR), Gg: hill(C, A.icG, A.hG) };
}
export const diam = (t, Gg) => A.dmax * Gg / (1 + Math.exp(-(t - A.t50) / A.s));
export const lightK = (t) => (t <= A.dark ? 0 : 1 - Math.exp(-(t - A.dark) / A.tauL));

/** Пуассонівська випадкова величина (метод Кнута; для великих λ — нормальне наближення). */
export function poisson(lam, R) {
  if (lam > 30) { let u = 0, v = 0; while (!u) u = R(); v = R(); return Math.max(0, Math.round(lam + Math.sqrt(lam) * Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * v))); }
  const L = Math.exp(-lam); let k = 0, p = 1; do { k++; p *= R(); } while (p > L); return k - 1;
}

/* ---------- Сублетальна концентрація і стабільність ---------- */
export const B = {
  LC50: 150, h: 4,     // NaCl, мМ: виживання колоній — припущення
  IC50: 120, hg: 2,    // ріст тих, що вижили
  kA: 1.6, kG: 2.2,    // у скільки разів стійкіші адаптовані (фізіологічно) і генетично стійкі клітини
  adapt: 0.5,          // імовірність фізіологічної адаптації чутливого калюсу, що вижив на пасажі
  revert: 0.6,         // імовірність втрати адаптації за пасаж без селективного фактора
  qG: 0.06,            // частка експлантатів, що несуть генетично стійкий сектор
  N0: 48,              // калюсів на старті (4 чашки × 12)
};
export const surv = (c) => hill(c, B.LC50, B.h);
export const growth = (c) => hill(c, B.IC50, B.hg);
export const isSublethal = (c) => surv(c) >= 0.2 && surv(c) <= 0.8 && growth(c) >= 0.4;

/** План пасажів: [{kind:'sel'|'non'|'ret', c}] */
export function schedule({ c, scheme, nSel, nNon }) {
  const out = [];
  for (let i = 0; i < nSel; i++) out.push({ kind: 'sel', c: scheme === 'step' ? c * Math.min(1, 0.5 + 0.25 * i) : c });
  for (let i = 0; i < nNon; i++) out.push({ kind: 'non', c: 0 });
  out.push({ kind: 'ret', c });
  return out;
}
/** Перехід одного клону за пасаж: стан 'S' (чутливий) | 'A' (фізіологічно адаптований) | 'G' (генетично стійкий) |
 *  'D' (загинув) | 'X' (вижив при поверненні, але чутливий — відбраковано). R — генератор 0..1. */
export function stepClone(st, P, R) {
  if (st === 'D' || st === 'X') return st;
  if (P.kind === 'non') return st === 'A' && R() < B.revert ? 'S' : st;
  if (st === 'G') return R() < surv(P.c / B.kG) ? 'G' : 'D';
  if (st === 'A') return R() < surv(P.c / B.kA) ? 'A' : 'D';
  if (R() >= surv(P.c)) return 'D';
  if (P.kind === 'ret') return 'X';        // чутливий: росте погано, у стабільні лінії не відбирають
  return R() < B.adapt ? 'A' : 'S';
}
/** Очікувані частки станів по пасажах (детерміновано). */
export function expected(plan) {
  let s = { S: 1 - B.qG, A: 0, G: B.qG, D: 0, X: 0 };
  const rows = [{ ...s }];
  for (const P of plan) {
    const n = { S: 0, A: 0, G: 0, D: s.D, X: s.X };
    if (P.kind === 'non') { n.G = s.G; n.A = s.A * (1 - B.revert); n.S = s.S + s.A * B.revert; }
    else {
      const sg = surv(P.c / B.kG), sa = surv(P.c / B.kA), ss = surv(P.c);
      n.G = s.G * sg;
      if (P.kind === 'ret') { n.A = s.A * sa; n.X += s.S * ss; n.S = 0; }
      else { n.A = s.A * sa + s.S * ss * B.adapt; n.S = s.S * ss * (1 - B.adapt); }
      n.D += s.G * (1 - sg) + s.A * (1 - sa) + s.S * (1 - ss);
    }
    s = n; rows.push({ ...s });
  }
  return rows;
}
