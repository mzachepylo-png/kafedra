// перевірити окремо (node). Сторінки посібника (Мельничук, Кляченко, 2014) вказано біля кожного блоку.
// Де посібник дає лише якісну закономірність, використано правдоподібне наближення (позначено «модель»).

export const clamp = (x, a, b) => Math.max(a, Math.min(b, x));
export const smooth = (a, b, x) => { const t = clamp((x - a) / (b - a), 0, 1); return t * t * (3 - 2 * t); };

/* =====================================================================================
 * 1. Апікальна меристема й оздоровлення (ЛР 26–28, с. 111–112, 115–119)
 * Імовірність того, що експлантат довжиною L (від верхівки купола до зрізу) вільний від вірусу:
 *   P_вф(L) = exp(−(L/λ)²),
 * де λ — «глибина» безвірусної зони апекса. λ₀ підібрано за контрольними точками посібника (с. 111):
 *   меристема картоплі 200 мкм → лише 10 % рослин без X-вірусу; ураженість Y-вірусом 70 % (тобто 30 % вільних):
 *   λ₀(X) = 200/√ln10 = 131,8 мкм;  λ₀(Y) = 200/√ln(1/0,3) = 182,3 мкм.
 * Для вірусів гвоздики (CarMV, CarVMV, с. 111: «одержані інфіковані мериклони») λ₀ — оцінка моделі.
 * Термотерапія (с. 112, 118): підйом від +25 °C на 2 °C за добу, далі +37 °C; ефективна доза — доба при +37 °C,
 *   інші температури зважено коефіцієнтом Q₁₀ = 3 (модель). λ = λ₀·(1 + k_T·d_еф).
 * Хіміотерапія вірозолом 20–50 мг/л (с. 112): λ множиться на (1 + C/9 мг/л) — так, щоб при 200 мкм і 20 мг/л
 *   частка безвірусних меристем становила ≈ 80 %, а при 50 мг/л — понад 90 % («80–100 %», с. 112).
 * Приживлюваність (регенерація пагона) зростає з розміром: P_рег = 1 − exp(−(L/λ_р)²) (модель; λ_р ≈ 200–220 мкм,
 *   звідси діапазон 100–250 мкм як компроміс, с. 117). Фітотоксичність вірозолу: 1/(1 + (C/80)²) (модель).
 * ===================================================================================== */
export const VIRUSES = {
  pvx: { crop: 'potato', short: 'X-вірус картоплі', abbr: 'ХВК', lam0: 200 / Math.sqrt(Math.log(10)), kT: 0.025 },
  pvy: { crop: 'potato', short: 'Y-вірус картоплі', abbr: 'YВК', lam0: 200 / Math.sqrt(Math.log(1 / 0.3)), kT: 0.035 },
  carmv: { crop: 'carn', short: 'вірус крапчастості гвоздики', abbr: 'CarMV', lam0: 110, kT: 0.02 },
  carvmv: { crop: 'carn', short: 'вірус крапчастості жилок гвоздики', abbr: 'CarVMV', lam0: 160, kT: 0.035 },
};
export const LAM_REG = { potato: 220, carn: 200 };

/** Температурний режим термотерапії: доба i → °C (підйом від +25 на 2 °C/добу до цільової, с. 112). */
export function thermoTemp(day, Tset) { return Math.min(Tset, 25 + 2 * (day + 1)); }

/** Ефективна теплова доза (доби при +37 °C) і виживання рослини-донора за D діб при цільовій T. */
export function heatDose(D, Tset) {
  let deff = 0, harm = 0;
  for (let i = 0; i < Math.round(D); i++) {
    const T = thermoTemp(i, Tset);
    deff += Math.pow(3, (T - 37) / 10);
    if (T > 30) harm += 0.004 * Math.exp(0.6 * (T - 37)); // модель: пригнічення росту тривалим нагріванням (с. 112)
  }
  return { deff, survive: Math.exp(-harm) };
}

export function meristem({ virus = 'pvx', L = 200, D = 0, T = 37, C = 0 }) {
  const v = VIRUSES[virus];
  const { deff, survive } = heatDose(D, T);
  const lam = v.lam0 * (1 + v.kT * deff) * (1 + C / 9);
  const lr = LAM_REG[v.crop];
  const tox = 1 / (1 + Math.pow(C / 80, 2));
  const pvf = (l) => Math.exp(-Math.pow(l / lam, 2));
  const preg = (l) => (1 - Math.exp(-Math.pow(l / lr, 2))) * tox;
  let Lopt = 50, Ymax = 0;
  for (let l = 40; l <= 1000; l += 2) { const y = pvf(l) * preg(l); if (y > Ymax) { Ymax = y; Lopt = l; } }
  return { lam, lr, tox, deff, survive, Pvf: pvf(L), Preg: preg(L), Y: pvf(L) * preg(L), Lopt, Ymax, pvf, preg };
}

/* =====================================================================================
 * 2. Мікроживцювання (ЛР 30, с. 121) і прискорене мікророзмноження (ЛР 32, с. 124–125)
 * Черенкування кожні τ = 14–21 доба, з однієї рослини k = 5–8 живців (с. 121). Якщо всі живці знову йдуть
 * у розмноження, після n пасажів — геометрична прогресія:  N_n = N₀·Kⁿ,  K = k·(1 − q)  (q — частка втрат).
 * n = ⌊(T − t₀)/τ⌋, t₀ — час отримання першої рослини з меристеми (30–45 діб, с. 117).
 * Узагальнення: частку p живців залишають маточним фондом, решту (1 − p) — на укорінення й висаджування:
 *   M_n = N₀·(pK)ⁿ;  на укорінення за n пасажів O = (1 − p)·K·N₀·((pK)ⁿ − 1)/(pK − 1);
 *   усього нарізано живців S = K·N₀·((pK)ⁿ − 1)/(pK − 1) (сума геометричної прогресії). При p = 1: N = N₀·Kⁿ.
 * Термотерапія маточних рослин підвищує K на 50–60 % (с. 112) — множник 1,5.
 * Прискорене (ЛР 32): індукція бруньок БАП 4–6 мг/л 2–3 тиж., далі пасажі по 14 діб на БАП ≤ 2 мг/л,
 *   укорінення на ІОК 0,1–0,2 мг/л. Модель: пагонів на експлантат за пасаж
 *   K(B) = 1 + 9·B^1,5/(1,5^1,5 + B^1,5), частка гіпергідричних (оскліловілих) пагонів v(B) = x³/(1 + x³), x = B/4,5;
 *   частка експлантатів, що перейшли до проліферації, P_інд(B₁) = B₁²/(9 + B₁²)/(1 + (B₁/9)⁴).
 * ===================================================================================== */
export function cutting({ N0 = 1, k = 6, q = 0.1, tau = 21, T = 365, t0 = 45, thermo = false, p = 1 }) {
  const K = k * (1 - q) * (thermo ? 1.5 : 1);
  const n = Math.max(0, Math.floor((T - t0) / tau));
  const r = p * K;                                  // знаменник прогресії маточного фонду
  const gsum = (m) => (Math.abs(r - 1) < 1e-9 ? m : (Math.pow(r, m) - 1) / (r - 1)); // 1 + r + … + r^(m−1)
  const M = N0 * Math.pow(r, n);                    // маточний фонд після n пасажів
  const O = (1 - p) * K * N0 * gsum(n);             // живці, віддані на укорінення за всі пасажі
  const S = K * N0 * gsum(n);                       // усього нарізано живців (трудомісткість)
  return { K, r, n, M, O, N: M + O, S };
}
/** Динаміка за пасажами: [{i, day, M, total}] */
export function cuttingSeries(o) {
  const { K, r } = cutting(o), res = [];
  const p = o.p ?? 1, N0 = o.N0 ?? 1;
  let M = N0, O = 0;
  for (let i = 0; ; i++) {
    const day = (o.t0 ?? 45) + i * o.tau;
    if (day > o.T + 1e-9) break;
    res.push({ i, day, M, total: M + O });
    O += (1 - p) * K * M; M *= r;
  }
  return res;
}
export function passagesFor(Ntarget, N0, K) { return K <= 1 ? Infinity : Math.max(0, Math.ceil(Math.log(Ntarget / N0) / Math.log(K) - 1e-9)); }

export const accK = (B) => 1 + 9 * Math.pow(B, 1.5) / (Math.pow(1.5, 1.5) + Math.pow(B, 1.5));
export const accV = (B) => { const x = Math.pow(B / 4.5, 3); return x / (1 + x); };
export const accInd = (B1) => (B1 * B1 / (9 + B1 * B1)) / (1 + Math.pow(B1 / 9, 4));
export function accelerated({ N0 = 1, B1 = 5, B2 = 2, q = 0.1, T = 365, tInd = 21, tRoot = 28, rootRate = 0.9 }) {
  const Kp = accK(B2) * (1 - accV(B2)) * (1 - q);
  const Pind = accInd(B1);
  const n = Math.max(0, Math.floor((T - tInd - tRoot) / 14));
  const N = N0 * Pind * Math.pow(Kp, n) * rootRate;
  return { Kp, Kraw: accK(B2), v: accV(B2), Pind, n, N };
}

/* =====================================================================================
 * 3. Мікробульби картоплі (ЛР 29, с. 119–120)
 * Середовище МС + кінетин 0,5 мг/л + сахароза 50 г/л (до 8 %, с. 119); перші 10–12 діб 16 год світла, далі 12 год,
 * вдень +25 °C, уночі +19–20 °C; або після довгого дня — охолодження до +10 °C. Бульби — через ≈ 1 місяць,
 * увесь цикл 60–65 діб. Сила індукції бульбоутворення S = f_сах·f_фото·f_цит (модель):
 *   f_сах = s⁴/(45⁴ + s⁴), за s > 80 г/л множиться на exp(−((s − 80)/40)²) (осмотичний стрес);
 *   f_цит = 0,6 + 0,4·c/(0,25 + c);  f_фото: 12 год + прохолодні ночі — 1; постійні 16 год і +25 °C — 0,45; +10 °C — 1,1.
 * Початок бульбоутворення t₁ = 18 + 7/S діб; маса m(t) = 400·S·(1 − e^(−(t − t₁)/14)) мг;
 * діаметр d = (6m/(πρ))^(1/3), ρ = 1,08 мг/мм³.
 * ===================================================================================== */
export const PHOTO = { sd: 1, ld: 0.45, cold: 1.1 };
export function tuber({ s = 50, c = 0.5, regime = 'sd' }) {
  let fs = Math.pow(s, 4) / (Math.pow(45, 4) + Math.pow(s, 4));
  if (s > 80) fs *= Math.exp(-Math.pow((s - 80) / 40, 2));
  const fc = 0.6 + 0.4 * c / (0.25 + c);
  const S = fs * fc * PHOTO[regime];
  const t1 = S > 0.02 ? 18 + 7 / S : Infinity;
  const mass = (t) => (t > t1 ? 400 * S * (1 - Math.exp(-(t - t1) / 14)) : 0);
  const diam = (m) => (m > 0 ? Math.cbrt(6 * m / (Math.PI * 1.08)) : 0);
  const count = Math.max(1, Math.round(0.6 + 2.6 * S));
  const share = t1 < 65 ? 1 - Math.exp(-3 * S) : 0;
  return { S, fs, fc, t1, mass, diam, count, share };
}

/* =====================================================================================
 * 4. Індукція коренеутворення (ЛР 31, с. 122–123)
 * Способи: ауксин 0,3–1 мг/л; розведення мінеральної основи вдвічі; затемнення основи (фольга, активоване вугілля);
 * невисока освітленість (1000 лк у рецепті). Модель:
 *   f_аукс = (0,25 + 0,75·C²/(0,15² + C²)) / (1 + (C/2)³)   — надоптимальні дози гальмують корені й дають калюс;
 *   активоване вугілля адсорбує ≈ 60 % ауксину: C_еф = 0,4·C;  f_мін = 1 для ½ МС, 0,75 для повного МС;
 *   f_світло = 1/(1 + (I_осн/4000)²), I_осн = I (без затемнення) або 0,05·I.
 * R = f_аукс·f_мін·f_світло; частка укорінених = (1 − e^(−3R))/(1 − e^(−3)); коренів на пагін 1 + 11R;
 * довжина кореня L(t) = 45·R·(1 − 0,5·κ)·(1 − e^(−(t − t_лаг)/9)) мм, t_лаг = 6 + 6(1 − R), κ — частка калюсу.
 * ===================================================================================== */
export function rooting({ C = 0.3, half = true, base = 'none', I = 1000 }) {
  const Ce = base === 'charcoal' ? 0.4 * C : C;
  const fa = (0.25 + 0.75 * Ce * Ce / (0.0225 + Ce * Ce)) / (1 + Math.pow(Ce / 2, 3));
  const fm = half ? 1 : 0.75;
  const Ib = base === 'none' ? I : 0.05 * I;
  const fl = 1 / (1 + Math.pow(Ib / 4000, 2));
  const R = fa * fm * fl;
  const share = (1 - Math.exp(-3 * R)) / (1 - Math.exp(-3));
  const callus = Ce * Ce / (0.64 + Ce * Ce);
  const nRoots = 1 + 11 * R;
  const lag = 6 + 6 * (1 - R);
  const len = (t) => (t > lag ? 45 * R * (1 - 0.5 * callus) * (1 - Math.exp(-(t - lag) / 9)) : 0);
  return { Ce, fa, fm, fl, R, share, callus, nRoots, lag, len };
}

/* =====================================================================================
 * 5. Адаптація ex vitro (с. 113–114, ЛР 33, с. 126)
 * Втрата води листком E = g·VPD·f_I; VPD (дефіцит тиску водяної пари, кПа) = e_s(T)·(1 − RH/100),
 *   e_s(T) = 0,6108·exp(17,27T/(T + 237,3)) — формула Тетенса.
 * Продихи пробіркових рослин погано закриваються, кутикула тонка (с. 114): g спадає від 1 до 0,25 у міру
 *   «загартування» H (доби з помітною сухістю повітря): g = 0,25 + 0,75·e^(−H/5), dH/dt = min(1, VPD/0,4).
 * Корені без кореневих волосків (с. 114): здатність поглинати воду U = u₀ + (1 − u₀)(1 − e^(−t/τ_к)).
 * Напруження σ = E/U; відносна оводненість RWC = 99 − 22·max(0, σ − 0,35) %; пошкодження
 *   dD/dt = max(0, (82 − RWC)/8)² (+0,15/доба загнивання, якщо агар не відмито); виживання = e^(−D/6). Гліцерин 50 % (с. 114) — g×0,4. (Модель.)
 * ===================================================================================== */
export const es = (T) => 0.6108 * Math.exp(17.27 * T / (T + 237.3));
export function rhInside(t, { proto, N, RH }) {
  if (proto === 'open') return RH;
  if (proto === 'fog') return t < 10 ? Math.max(RH, 95) : Math.max(RH, 95) + (RH - Math.max(RH, 95)) * clamp((t - 10) / 7, 0, 1);
  const o = clamp((t - 3) / N, 0, 1); // укриття: 3 доби закрите, далі відкривають поступово за N діб
  return Math.max(RH, 98 - (98 - RH) * o);
}
export function openFrac(t, { proto, N }) { return proto === 'cover' ? clamp((t - 3) / N, 0, 1) : 1; }
export function adapt({ proto = 'cover', N = 10, RH = 70, T = 22, I = 5000, glycerol = false, roots = 'good', washed = true, days = 30, dt = 0.05 }) {
  const u0 = roots === 'good' ? 0.4 : 0.2, tr = roots === 'good' ? 7 : 12;
  const fL = 0.4 + 0.6 * I / 5000;
  let H = 0, D = 0;
  const out = [];
  for (let t = 0; t <= days + 1e-9; t += dt) {
    const rh = rhInside(t, { proto, N, RH });
    const vpd = es(T) * (1 - rh / 100);
    let g = 0.25 + 0.75 * Math.exp(-H / 5);
    if (glycerol) g *= 0.4;
    let U = u0 + (1 - u0) * (1 - Math.exp(-t / tr));
    if (!washed) U *= 1 - 0.45 * smooth(2, 10, t);
    const E = g * vpd * fL, sig = E / U;
    const rwc = clamp(99 - 22 * Math.max(0, sig - 0.35), 30, 99);
    out.push({ t, rh, vpd, g, U, E, sig, rwc, surv: 100 * Math.exp(-D / 6), D });
    H += dt * Math.min(1, vpd / 0.4);
    D += dt * (Math.pow(Math.max(0, (82 - rwc) / 8), 2) + (washed ? 0 : 0.15 * smooth(3, 6, t)) + 0.004 * Math.pow(Math.max(0, Math.abs(T - 22.5) - 2.5), 2));
  }
  return out;
}

/* =====================================================================================
 * 6. Ростові характеристики регенерантів (ЛР 34, с. 127; ЛР 30, с. 121)
 * Довжина — логістична крива, зсунута так, щоб L(0) = L₀:  f(t) = 1/(1 + e^(−r(t − t_m))),
 *   L(t) = L₀ + (L_max − L₀)·(f(t) − f(0))/(1 − f(0)).
 * Індекс росту I = L_t/L₀ (с. 127); вузлів = ⌊(L − 1)/l_м⌋, l_м — довжина міжвузля (етіоляція за слабкого світла);
 * сира маса FW = 0,9·L^1,45 мг (модель), суха маса DW ≈ 7,5 % FW; коефіцієнт розмноження — кількість мікроживців
 * з рослини: ⌊вузлів/b⌋, b = 1 брунька на живець у гвоздики, 2 — у картоплі (с. 121).
 * ===================================================================================== */
export const CROPS6 = {
  potato: { Lmax: 85, r: 0.17, tm: 20, inter: 6, buds: 2, opposite: false },
  carn: { Lmax: 65, r: 0.13, tm: 22, inter: 5, buds: 1, opposite: true },
};
export function growthLaw(L0, Lmax, r, tm) {
  const f = (t) => 1 / (1 + Math.exp(-r * (t - tm))), f0 = f(0);
  return (t) => L0 + (Lmax - L0) * (f(t) - f0) / (1 - f0);
}
export function lightFactors(I) {
  return { rate: 1 - 0.15 * Math.pow((I - 3000) / 2000, 2), inter: 1.4 - 0.1 * I / 1000, pale: 0.4 * smooth(3500, 5000, I) };
}
